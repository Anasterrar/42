#include "ft_cat.h"

void	error(char *fileName, char *errorMessage)
{
	ft_putstr_fd("ft_cat: ", 2);
	ft_putstr_fd(fileName, 2);
	ft_putstr_fd(": ", 2);
	ft_putstr_fd(errorMessage, 2);
	ft_putchar_fd('\n', 2);
}
