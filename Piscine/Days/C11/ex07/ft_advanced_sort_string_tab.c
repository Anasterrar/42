void ft_advanced_sort_string_tab(char **tab, int(*cmp)(char *, char *))
{
        int             i;
        int             y;
        char    *tmp;

        i = 0;
        while (tab[i + 1] != NULL)
        {
                y = i + 1;
                while (tab[y] != NULL)
                {
                        if (cmp(tab[i], tab[y]) > 0)
                        {
                                tmp = tab[i];
                                tab[i] = tab[y];
                                tab[y] = tmp;
                        }
                        y++;
                }
                i++;
        }
}
