#include "ft_do_op.h"

int	add(int a, int b)
{
	return (a + b);
}

int	sub(int a, int b)
{
	return (a - b);
}

int	divid(int a, int b)
{
	return (a / b);
}

int	mult(int a, int b)
{
	return (a * b);
}

int	mod(int a, int b)
{
	return (a % b);
}
